def vt(c, span=0.07):
    """同一 id 的第几个变体在音高与体量上的偏移，让变体彼此可辨。"""
    n = getattr(c, "n_variants", 1)
    return 1.0 + span * (c.v - (n - 1) * 0.5)


def cry(c, K, dur, pts, env_pts, sub=0.0, rough=0.35, drive=1.5):
    """按种类的共振峰与音高发一声虫鸣。"""
    k = vt(c, 0.06)
    pts = [(u, f * k) for u, f in pts]
    return voice(c.rng, dur, pts, 0.02, (0.0, 30.0), rough, 70.0, K["form"], 0.3, "pulse", 0.18, drive, sub, env_pts)


def body_hit(c, K, dur=0.4, scale=1.0):
    """甲壳或躯体被击中的一次性冲击。"""
    k = vt(c, 0.09)
    return thump(c.rng, K["body"] * scale * k, K["body"] * 0.42 * scale * k, dur, dur * 0.22, 0.012, 2.0, 0.25)


def chitin_knock(c, K, scale=1.0):
    """甲壳敲击：干硬的模态响声。"""
    return clank(c.rng, K["body"] * 2.6 * scale * vt(c, 0.1), 0.06, PLATE, 0.3, 0.75, 0.35, 7000.0)


def glass_ring(c, K, scale=1.0):
    """晶体被激励后的清脆余响。"""
    return modal(c.rng, K["f0"] * 1.9 * scale * vt(c, 0.08), [1.0, 2.4, 3.9, 5.7, 7.3], 0.35, 1.2, 0.02, 0.6, 0.5)



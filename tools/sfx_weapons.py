def outdoor_slaps(c, x, times, gains, cut=1350.0):
    """户外远场漫反射低频余音（经过强低通与微噪声包络柔化，绝不产生双响枪声或金属梳状滤波）。"""
    m = Mix()
    m.add(x)
    mono = x if x.ndim == 1 else x.mean(axis=1)
    n = len(mono)
    # 远场反射只保留低中频气浪，叠加随机扩散包络
    src_ = lp(mono, cut, 2) * (0.65 + 0.35 * np.abs(smooth_noise(n, c.rng, 16.0)))
    for t_s, g in zip(times, gains):
        m.add(src_, c.j(t_s, 0.08), g * 0.45)
    return m.render()


